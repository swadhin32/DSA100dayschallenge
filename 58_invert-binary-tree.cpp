// Invert Binary Tree
// Pattern: Tree Recursion

// Problem Statement:
// Given the root of a binary tree, invert the tree and return its root.

// Inversion means:

// left child becomes right child
// right child becomes left child

// Example:

// Input:
// 4
// /
// 2 7
// / \ /
// 1 3 6 9

// Output:
// 4
// /
// 7 2
// / \ /
// 9 6 3 1

// Explanation:
// Every node swaps its left and right children.

// Core Concepts:
// ✅ Tree Recursion
// ✅ DFS Traversal
// ✅ Swapping Subtrees
// ✅ Recursive Tree Modification

// Main Logic:
// At every node:

// swap left and right
// recursively invert children

// ━━━━━━━━━━━━━━━━━━

